/* 评审视角账本 —— 这套东西的**目标函数**。
 *
 * 为什么要有这一份，以及为什么它必须和 UE5 能力账本并列：
 *
 * 上一版整套提示词的隐含目标是「设计一个好玩的游戏」。那是错的。
 * 主人原话：「这个游戏不是给我玩的，是打比赛用的」「我喜欢什么不重要，
 * 能让裁判 / HR 感到不错，能聊得来，有搞头就行」。
 *
 * 这两句话把优化目标整个换掉了：
 *
 *   旧目标：玩家玩三十小时觉得值 → 深度、内容量、长线循环、留存
 *   新目标：**评委看三十秒觉得没见过，面试官聊三十分钟觉得你有货**
 *
 * 这两个目标在很多地方是**冲突**的，不是「顺带也能满足」。举例：
 *
 *   - 「上手难、后期爽」对玩家是优点，对评委是灾难 —— 他根本到不了后期。
 *   - 「系统层层嵌套的深度」对玩家是价值，对评委是噪音 —— 他看不懂。
 *   - 「打磨手感」值得投三十人日，但它**在截图里不存在**，评委翻页就过去了。
 *   - 反过来「一个视觉上没见过的东西」对玩家可能只新鲜五分钟，
 *     但它是评委唯一会记住的东西，也是面试官唯一会追问的东西。
 *
 * 所以：**别拿这一份当「顺便也要考虑一下」。它就是评分标准本身。**
 *
 * ⚠️ 这份账本描述的是评审场景的一般规律。具体到某个比赛的评分表，
 *    总纲第四节里有主人填的比赛信息 —— 那一节永远优先于这一份。
 */

