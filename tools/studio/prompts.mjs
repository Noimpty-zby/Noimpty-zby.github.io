export const parseShortlist = raw => {
  const text = String(raw || '')
  const win = (text.match(/^\s*第一名\s*[:：]\s*(.+)$/m) || [])[1]
  if (!win) return null
  const num = name => {
    const m = text.match(new RegExp(`^\\s*${name}\\s*[:：]\\s*(\\d)`, 'm'))
    return m ? Number(m[1]) : 3
  }
  const outLine = (text.match(/^\s*淘汰\s*[:：]\s*(.+)$/m) || [])[1] || ''
  const out = /^\s*无\s*$/.test(outLine.trim()) ? [] :
    outLine.split(/[；;、]/).map(s => s.trim()).filter(Boolean)
  return {
    winner: win.trim(),
    dims: { glance: num('一眼可辨'), talk: num('技术讲点'), ship: num('可完成'), unique: num('独特') },
    dropped: out
  }
}

