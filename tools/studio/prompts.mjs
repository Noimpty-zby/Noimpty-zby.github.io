/** 从校验输出里取判定。取不到返回 null —— 调用方按「拦下」处理。 */
export const parseAudit = raw => {
  const text = String(raw || '')
  const m = text.match(/^\s*判定\s*[:：]\s*(通过|否决|存疑)/m)
  if (!m) return null
  const why = (text.match(/^\s*致命冲突\s*[:：]\s*(.+)$/m) || [])[1] || ''
  return { verdict: m[1], why: why.trim().slice(0, 200), passed: m[1] === '通过' }
}

